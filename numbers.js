// 1. Create variables for favorite numbers
let firstFavNum = 7;
let secondFavNum = 30;

// 2. Perform mathematical operations

// Addition
let sum = firstFavNum + secondFavNum;
console.log("Addition:", sum);

// Subtraction
let difference = firstFavNum - secondFavNum;
console.log("Subtraction:", difference);

// Multiplication
let product = firstFavNum * secondFavNum;
console.log("Multiplication:", product);

// Division
let quotient = firstFavNum / secondFavNum;
console.log("Division:", quotient);

// Modulus (Remainder)
let remainder = firstFavNum % secondFavNum;
console.log("Modulus:", remainder);

// Exponentiation (Power)
let power = firstFavNum ** 2; // example: firstFavNum squared
console.log("Exponentiation (firstFavNum squared):", power);
